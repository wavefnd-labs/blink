"""Regenerate tiny project-authored native rendering fixtures.

This is an optional maintainer tool, never a build prerequisite. Regeneration
uses fontTools (verified with 4.61.1) and Pillow (verified with 11.3.0). No font
or image from a third party is copied: every outline and pixel is defined here.
"""

from __future__ import annotations

import argparse
import base64
from io import BytesIO
from pathlib import Path
import struct
import zlib


def font_bytes() -> bytes:
    from fontTools.feaLib.builder import addOpenTypeFeaturesFromString
    from fontTools.fontBuilder import FontBuilder
    from fontTools.pens.ttGlyphPen import TTGlyphPen

    order = [".notdef", "space", "A", "B", "A.ss02", "A.hist"]
    builder = FontBuilder(1000, isTTF=True)
    builder.setupGlyphOrder(order)
    builder.setupCharacterMap({32: "space", 65: "A", 66: "B"})
    glyphs = {}
    # Distinct positions make ss02/hist substitution measurable in RGBA output.
    metrics = {"space": (1000, 0)}
    for name, left, width, top in [
            (".notdef", 50, 250, 700), ("A", 100, 250, 700),
            ("B", 150, 300, 600), ("A.ss02", 550, 350, 700),
            ("A.hist", 325, 250, 550)]:
        pen = TTGlyphPen(None)
        pen.moveTo((left, 100))
        pen.lineTo((left + width, 100))
        pen.lineTo((left + width, top))
        pen.lineTo((left, top))
        pen.closePath()
        # Reversed inner contour leaves a white window in each black rectangle.
        pen.moveTo((left + 70, 250))
        pen.lineTo((left + 70, top - 150))
        pen.lineTo((left + 180, top - 150))
        pen.lineTo((left + 180, 250))
        pen.closePath()
        glyphs[name] = pen.glyph()
        metrics[name] = (1000, left)
    glyphs["space"] = TTGlyphPen(None).glyph()
    builder.setupGlyf(glyphs)
    builder.setupHorizontalMetrics(metrics)
    builder.setupHorizontalHeader(ascent=800, descent=-200)
    builder.setupNameTable({
        "familyName": "Wave Smoke Features", "styleName": "Regular",
        "uniqueFontIdentifier": "WaveSmokeFeatures-2026-1",
        "fullName": "Wave Smoke Features Regular",
        "psName": "WaveSmokeFeatures-Regular", "version": "Version 1.000",
        "copyright": "Copyright 2026 The Blink Standalone Authors",
        "licenseDescription": "BSD-3-Clause; see the project LICENSE file.",
    })
    builder.setupOS2(sTypoAscender=800, sTypoDescender=-200,
                     usWinAscent=800, usWinDescent=200)
    builder.setupPost()
    builder.setupMaxp()
    builder.setupHead(created=2082844800, modified=2082844800)
    addOpenTypeFeaturesFromString(builder.font, """
        languagesystem DFLT dflt;
        feature ss02 { sub A by A.ss02; } ss02;
        feature hist { sub A by A.hist; } hist;
    """)
    builder.font.recalcTimestamp = False
    output = BytesIO()
    builder.font.save(output, reorderTables=True)
    return output.getvalue()


def png_bytes() -> bytes:
    def chunk(kind: bytes, data: bytes) -> bytes:
        return (struct.pack(">I", len(data)) + kind + data +
                struct.pack(">I", zlib.crc32(kind + data)))

    return (b"\x89PNG\r\n\x1a\n" +
            chunk(b"IHDR", struct.pack(">IIBBBBB", 2, 2, 8, 2, 0, 0, 0)) +
            chunk(b"IDAT", zlib.compress(b"\0\xff\0\0\xff\0\0" * 2, 9)) +
            chunk(b"IEND", b""))


def pillow_bytes(format_name: str, color: tuple[int, int, int]) -> bytes:
    from PIL import Image

    output = BytesIO()
    options = ({"quality": 100, "subsampling": 0, "optimize": False}
               if format_name == "JPEG" else {"lossless": True, "exact": True})
    Image.new("RGB", (2, 2), color).save(output, format=format_name, **options)
    return output.getvalue()


def header_bytes() -> bytes:
    fixtures = {
        "kRedPng": png_bytes(),
        "kGreenJpeg": pillow_bytes("JPEG", (0, 255, 0)),
        "kBlueWebp": pillow_bytes("WEBP", (0, 0, 255)),
        "kFeatureFont": font_bytes(),
    }
    lines = [
        "// Copyright 2026 The Blink Standalone Authors. BSD-3-Clause; see /LICENSE.",
        "// Generated by standalone/tools/generate_rendering_fixtures.py.",
        "// Original project-authored pixels and outlines; no imported font data.",
        "#ifndef BLINK_STANDALONE_ENGINE_RENDERING_FIXTURES_H_",
        "#define BLINK_STANDALONE_ENGINE_RENDERING_FIXTURES_H_", "",
        "#include <cstdint>", "", "namespace blink_standalone::smoke::fixtures {",
    ]
    for name, value in fixtures.items():
        lines.append(f"inline constexpr uint8_t {name}[] = {{")
        for start in range(0, len(value), 12):
            lines.append("    " + ", ".join(f"0x{item:02x}" for item in
                                             value[start:start + 12]) + ",")
        lines.extend(["};", ""])
    data_url = "data:image/png;base64," + base64.b64encode(fixtures["kRedPng"]).decode()
    lines.append("inline constexpr char kRedPngDataUrl[] =")
    for start in range(0, len(data_url), 70):
        suffix = ";" if start + 70 >= len(data_url) else ""
        lines.append(f'    "{data_url[start:start + 70]}"{suffix}')
    lines.extend(["", "}  // namespace blink_standalone::smoke::fixtures", "",
                  "#endif  // BLINK_STANDALONE_ENGINE_RENDERING_FIXTURES_H_", ""])
    return "\n".join(lines).encode()


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true",
                        help="compare regenerated bytes without writing")
    parser.add_argument("--output", type=Path,
                        default=Path(__file__).resolve().parents[1] /
                        "engine/rendering_fixtures.h")
    arguments = parser.parse_args()
    generated = header_bytes()
    if arguments.check:
        if arguments.output.read_bytes() != generated:
            parser.error(f"fixture bytes differ: {arguments.output}")
    else:
        arguments.output.write_bytes(generated)
    print(f"Verified {len(generated)} generated fixture header bytes")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
