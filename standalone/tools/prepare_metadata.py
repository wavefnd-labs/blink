#!/usr/bin/env python3
"""Generate selected library revision headers using the pinned upstream tool."""
import hashlib
import importlib.util
import json
import os
from pathlib import Path
import subprocess
import sys
import tempfile

import materialize

ROOT, SUPPORT, SRC = materialize.ROOT, materialize.SUPPORT, materialize.SRC


def verify_output(path, revision, macro=None):
    text = path.read_text()
    if macro:
        marker = '#define ' + macro + ' "' + revision
        if marker not in text or '/* Generated by lastchange.py, do not edit.*/' not in text:
            raise ValueError('Generated metadata does not contain the pinned revision: ' + str(path))
    elif not text.startswith(revision):
        raise ValueError('Generated revision is not the pinned dependency: ' + str(path))


def main():
    lock = materialize.read_json(SUPPORT / 'config/dependencies.lock.json')
    pin = lock['chromium_revision']
    upstream = materialize.read_json(SUPPORT / 'config/upstream.lock.json')
    if pin != upstream['revision']:
        raise ValueError('Metadata and source revisions differ')
    deps_bytes = (SRC / 'DEPS').read_bytes()
    if hashlib.sha256(deps_bytes).hexdigest() != lock['root_deps_sha256']:
        raise ValueError('Original DEPS metadata changed')
    spec = importlib.util.spec_from_file_location('metadata_hydration', SUPPORT / 'tools/graph/hydrate.py')
    hydration = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(hydration)
    script = SRC / 'build/util/lastchange.py'
    original = hydration.git(hydration.CACHE, 'show', pin + ':build/util/lastchange.py',
                             env={**os.environ, 'GIT_NO_LAZY_FETCH': '1'})
    if script.read_bytes() != original:
        raise ValueError('Original lastchange generator changed')
    recipes = [
        {'hook': 'gpu_lists_version', 'source': '.', 'revision': pin,
         'macro': 'GPU_LISTS_VERSION', 'header': 'gpu/config/gpu_lists_version.h', 'id_only': True},
        {'hook': 'lastchange_skia', 'source': 'third_party/skia',
         'revision': lock['dependencies']['third_party/skia']['revision'],
         'macro': 'SKIA_COMMIT_HASH', 'header': 'skia/ext/skia_commit_hash.h'},
        {'hook': 'lastchange_dawn', 'source': 'third_party/dawn',
         'revision': lock['dependencies']['third_party/dawn']['revision'],
         'macro': 'DAWN_COMMIT_HASH', 'header': 'gpu/webgpu/dawn_commit_hash.h',
         'revision_file': 'gpu/webgpu/DAWN_VERSION'},
    ]
    report = {'chromium_revision': pin, 'compiled': False, 'complete': False,
              'root_deps_sha256': lock['root_deps_sha256'],
              'generator': 'build/util/lastchange.py', 'generator_sha256': hashlib.sha256(original).hexdigest(),
              'policy': 'Only reviewed revision-metadata hooks; no general DEPS hook execution or source compilation',
              'outputs': {}}
    work = SUPPORT / 'work/graph'
    with tempfile.TemporaryDirectory(prefix='metadata-', dir=work) as temporary:
        stage = Path(temporary) / 'src'
        generated = []
        for recipe in recipes:
            source = SRC / recipe['source']
            actual = subprocess.check_output(['git', '-C', str(source), 'rev-parse', 'HEAD'], text=True).strip()
            if actual != recipe['revision']:
                raise ValueError('Metadata source is not the pinned dependency: ' + recipe['source'])
            header = stage / recipe['header']
            header.parent.mkdir(parents=True, exist_ok=True)
            command = [sys.executable, '-B', str(script), '-m', recipe['macro'],
                       '-s', str(source), '--header', str(header)]
            if recipe.get('id_only'):
                command.append('--revision-id-only')
            if recipe.get('revision_file'):
                revision_file = stage / recipe['revision_file']
                command.extend(['--revision', str(revision_file)])
            env = {key: value for key, value in os.environ.items() if key != 'BASE_COMMIT_SUBMISSION_MS'}
            subprocess.run(command, cwd=SRC, env=env, check=True)
            verify_output(header, recipe['revision'], recipe['macro'])
            generated.append((recipe['header'], recipe))
            if recipe.get('revision_file'):
                verify_output(revision_file, recipe['revision'])
                generated.append((recipe['revision_file'], recipe))
        # Validate every output before publishing any generated file.
        for name, _ in generated:
            materialize.check_parents(SRC, name)
            path = SRC / name
            if os.path.lexists(path) and (path.is_symlink() or not path.is_file() or path.read_bytes() != (stage / name).read_bytes()):
                raise ValueError('Existing generated metadata differs; preserve and review: ' + name)
        for name, recipe in generated:
            target = SRC / name
            target.parent.mkdir(parents=True, exist_ok=True)
            if not target.exists():
                materialize.install_file(target, '100644', source=stage / name)
            report['outputs'][name] = {'sha256': hashlib.sha256(target.read_bytes()).hexdigest(),
                                       'revision': recipe['revision'], 'upstream_hook': recipe['hook']}
    report['complete'] = True
    materialize.write_json(SUPPORT / 'reports/linux-x64-generated-metadata.json', report)
    print('Generated and verified four pinned GPU/Skia/Dawn revision metadata files; no compilation', flush=True)
    return 0


if __name__ == '__main__':
    try:
        sys.exit(main())
    except (OSError, ValueError, subprocess.CalledProcessError) as error:
        print('error:', error, file=sys.stderr)
        sys.exit(2)
